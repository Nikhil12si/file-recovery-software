-- =============================================================================
-- schema.sql — Track C (Member 3), Module 1: persistence for authentication,
-- recovery sessions, recovered files, semantic search and reports.
--
-- Target: PostgreSQL 13+ (gen_random_uuid() is built in from 13; pgcrypto is
-- enabled for older servers). Apply with:
--     psql -U postgres -c "CREATE DATABASE file_recovery"
--     psql -U postgres -d file_recovery -f database/schema.sql
-- The FastAPI service also applies this file automatically to an empty DB.
--
-- Conventions
--   * UUID primary keys generated by the application (uuid4) with a DB default.
--   * TIMESTAMPTZ everywhere, stored in UTC.
--   * JSONB for contract payloads whose shape is owned by another track
--     (progress, totals, raw engine candidate) so schema changes stay local.
-- =============================================================================

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- -----------------------------------------------------------------------------
-- Users & authentication
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id              UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    email           TEXT        NOT NULL,
    password_hash   TEXT        NOT NULL,                    -- bcrypt, cost 12
    full_name       TEXT,
    phone_number    TEXT,
    role            TEXT        NOT NULL DEFAULT 'operator'
                                CHECK (role IN ('admin', 'operator', 'viewer')),
    is_active       BOOLEAN     NOT NULL DEFAULT TRUE,
    failed_logins   INTEGER     NOT NULL DEFAULT 0,
    locked_until    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_at   TIMESTAMPTZ,
    CONSTRAINT users_email_format CHECK (position('@' IN email) > 1)
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_uq ON users (lower(email));

-- One row per issued JWT (jti). Logout / password change revokes rows, which
-- gives server-side session persistence and revocation on top of stateless JWTs.
CREATE TABLE IF NOT EXISTS auth_sessions (
    id          UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id     UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    jti         TEXT        NOT NULL UNIQUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at  TIMESTAMPTZ NOT NULL,
    revoked_at  TIMESTAMPTZ,
    user_agent  TEXT,
    ip_address  TEXT
);
CREATE INDEX IF NOT EXISTS auth_sessions_user_idx ON auth_sessions (user_id, expires_at DESC);

-- -----------------------------------------------------------------------------
-- Recovery sessions (one per scan request)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS recovery_sessions (
    id                UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id           UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    label             TEXT        NOT NULL,
    mode              TEXT        NOT NULL CHECK (mode IN ('quick', 'deep')),
    target_scope      TEXT        NOT NULL CHECK (target_scope IN ('all', 'drive', 'folder')),
    sources           JSONB       NOT NULL DEFAULT '[]'::jsonb,   -- engine source specs
    folder_path       TEXT,
    scenario          TEXT        NOT NULL DEFAULT 'custom'
                                  CHECK (scenario IN ('accidental_delete', 'formatted_drive', 'corrupted_partition', 'custom')),
    file_types        JSONB       NOT NULL DEFAULT '[]'::jsonb,
    options           JSONB       NOT NULL DEFAULT '{}'::jsonb,
    status            TEXT        NOT NULL DEFAULT 'queued'
                                  CHECK (status IN ('queued', 'running', 'analyzing', 'completed', 'partial', 'failed', 'cancelled')),
    progress          JSONB       NOT NULL DEFAULT '{}'::jsonb,   -- contracts: rest-api scan_progress
    totals            JSONB       NOT NULL DEFAULT '{}'::jsonb,   -- files/bytes/high/medium/low/clusters
    health_warnings   JSONB       NOT NULL DEFAULT '[]'::jsonb,
    scan_summary      JSONB       NOT NULL DEFAULT '{}'::jsonb,   -- engine "scan", "sources", "statistics" blocks
    engine_scan_id    TEXT,
    engine_exit_code  INTEGER,
    candidates_path   TEXT,
    error             TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at        TIMESTAMPTZ,
    finished_at       TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS recovery_sessions_user_idx ON recovery_sessions (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS recovery_sessions_status_idx ON recovery_sessions (status);

-- Sector-proximity clusters ("deletion events") computed by the analysis engine.
CREATE TABLE IF NOT EXISTS deletion_clusters (
    id                  TEXT        PRIMARY KEY,                 -- "<session uuid>:c<n>"
    session_id          UUID        NOT NULL REFERENCES recovery_sessions (id) ON DELETE CASCADE,
    label               TEXT        NOT NULL,
    file_count          INTEGER     NOT NULL,
    total_bytes         BIGINT      NOT NULL,
    lba_start           BIGINT      NOT NULL,
    lba_end             BIGINT      NOT NULL,
    dominant_extension  TEXT        NOT NULL,
    time_start          TIMESTAMPTZ,
    time_end            TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS deletion_clusters_session_idx ON deletion_clusters (session_id, lba_start);

-- -----------------------------------------------------------------------------
-- Recovered (candidate) files
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS recovered_files (
    id                  UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id          UUID        NOT NULL REFERENCES recovery_sessions (id) ON DELETE CASCADE,
    candidate_id        TEXT        NOT NULL,                    -- engine candidate id
    source_id           TEXT        NOT NULL,
    method              TEXT        NOT NULL CHECK (method IN ('mft', 'fat', 'carve')),
    file_name           TEXT,
    suggested_name      TEXT,                                    -- semantic auto-name
    original_path       TEXT,
    extension           TEXT        NOT NULL DEFAULT '',
    mime_type           TEXT        NOT NULL DEFAULT 'application/octet-stream',
    size_bytes          BIGINT      NOT NULL CHECK (size_bytes >= 0),
    lba                 BIGINT      NOT NULL DEFAULT 0,
    absolute_lba        BIGINT      NOT NULL DEFAULT 0,
    fragment_count      INTEGER     NOT NULL DEFAULT 0,
    confidence          TEXT        NOT NULL CHECK (confidence IN ('high', 'medium', 'low')),
    confidence_score    SMALLINT    NOT NULL CHECK (confidence_score BETWEEN 0 AND 100),
    confidence_reasons  JSONB       NOT NULL DEFAULT '[]'::jsonb,
    cluster_id          TEXT        REFERENCES deletion_clusters (id) ON DELETE SET NULL,
    timestamps          JSONB       NOT NULL DEFAULT '{}'::jsonb,
    keywords            JSONB       NOT NULL DEFAULT '[]'::jsonb,
    candidate           JSONB       NOT NULL,                    -- full contract object (needed for restore)
    sample_path         TEXT,
    thumbnail_path      TEXT,
    text_excerpt        TEXT,
    preview_kind        TEXT        NOT NULL DEFAULT 'none' CHECK (preview_kind IN ('image', 'text', 'none')),
    restored            BOOLEAN     NOT NULL DEFAULT FALSE,
    restored_path       TEXT,
    sha256              TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT recovered_files_candidate_uq UNIQUE (session_id, candidate_id)
);
CREATE INDEX IF NOT EXISTS recovered_files_session_conf_idx ON recovered_files (session_id, confidence);
CREATE INDEX IF NOT EXISTS recovered_files_session_ext_idx  ON recovered_files (session_id, extension);
CREATE INDEX IF NOT EXISTS recovered_files_session_lba_idx  ON recovered_files (session_id, absolute_lba);
CREATE INDEX IF NOT EXISTS recovered_files_cluster_idx      ON recovered_files (cluster_id);

-- -----------------------------------------------------------------------------
-- Semantic index: keywords + extracted text, searchable across all sessions
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS semantic_index (
    file_id          UUID        PRIMARY KEY REFERENCES recovered_files (id) ON DELETE CASCADE,
    session_id       UUID        NOT NULL REFERENCES recovery_sessions (id) ON DELETE CASCADE,
    user_id          UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title            TEXT,                                       -- suggested / original name
    keywords_text    TEXT        NOT NULL DEFAULT '',            -- space separated keywords
    content_excerpt  TEXT        NOT NULL DEFAULT '',
    language         TEXT        NOT NULL DEFAULT 'en',
    tsv              TSVECTOR GENERATED ALWAYS AS (
                         setweight(to_tsvector('english', coalesce(title, '')), 'A') ||
                         setweight(to_tsvector('english', keywords_text), 'B') ||
                         setweight(to_tsvector('english', content_excerpt), 'C')
                     ) STORED,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS semantic_index_tsv_idx  ON semantic_index USING GIN (tsv);
CREATE INDEX IF NOT EXISTS semantic_index_user_idx ON semantic_index (user_id);

-- -----------------------------------------------------------------------------
-- Restore jobs
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS restore_jobs (
    id                 UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id         UUID        NOT NULL REFERENCES recovery_sessions (id) ON DELETE CASCADE,
    user_id            UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    destination        TEXT        NOT NULL,
    status             TEXT        NOT NULL DEFAULT 'queued'
                                   CHECK (status IN ('queued', 'running', 'completed', 'partial', 'failed', 'cancelled')),
    options            JSONB       NOT NULL DEFAULT '{}'::jsonb,
    total_files        INTEGER     NOT NULL DEFAULT 0,
    restored_files     INTEGER     NOT NULL DEFAULT 0,
    failed_files       INTEGER     NOT NULL DEFAULT 0,
    bytes_written      BIGINT      NOT NULL DEFAULT 0,
    items              JSONB       NOT NULL DEFAULT '[]'::jsonb,
    destination_check  JSONB,
    error              TEXT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at        TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS restore_jobs_session_idx ON restore_jobs (session_id, created_at DESC);

-- -----------------------------------------------------------------------------
-- Reports (ReportLab PDFs)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS reports (
    id          UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id  UUID        NOT NULL REFERENCES recovery_sessions (id) ON DELETE CASCADE,
    user_id     UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title       TEXT        NOT NULL,
    file_name   TEXT        NOT NULL,
    file_path   TEXT        NOT NULL,
    size_bytes  BIGINT      NOT NULL DEFAULT 0,
    summary     JSONB       NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS reports_session_idx ON reports (session_id, created_at DESC);

-- -----------------------------------------------------------------------------
-- Audit trail (who scanned / restored what)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS audit_log (
    id          BIGSERIAL   PRIMARY KEY,
    user_id     UUID        REFERENCES users (id) ON DELETE SET NULL,
    action      TEXT        NOT NULL,
    details     JSONB       NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS audit_log_user_idx ON audit_log (user_id, created_at DESC);

-- -----------------------------------------------------------------------------
-- Triggers
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS users_set_updated_at ON users;
CREATE TRIGGER users_set_updated_at BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Convenience view used by the history page.
CREATE OR REPLACE VIEW session_overview AS
SELECT s.id, s.user_id, s.label, s.mode, s.target_scope, s.status, s.created_at, s.finished_at,
       COUNT(f.id)                                         AS file_count,
       COALESCE(SUM(f.size_bytes), 0)                      AS total_bytes,
       COUNT(f.id) FILTER (WHERE f.confidence = 'high')    AS high_count,
       COUNT(f.id) FILTER (WHERE f.confidence = 'medium')  AS medium_count,
       COUNT(f.id) FILTER (WHERE f.confidence = 'low')     AS low_count,
       COUNT(f.id) FILTER (WHERE f.restored)               AS restored_count
FROM recovery_sessions s
LEFT JOIN recovered_files f ON f.session_id = s.id
GROUP BY s.id;

COMMIT;
