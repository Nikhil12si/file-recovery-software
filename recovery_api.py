import json
import os
import random
from typing import List
from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel

app = FastAPI(title="File Recovery API")

# Allow frontend wizard to access the backend
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

class ScanResult(BaseModel):
    id: int
    type: str
    offset: int
    suggested_name: str
    confidence: str

def dummy_nlp_auto_naming(file_type: str, offset: int) -> str:
    """
    Lightweight Semantic Auto-Naming Stub (e.g., YAKE! / FastEmbed mock).
    Simulates extracting 2-3 keywords from a dummy recovered text block.
    """
    keyword_corpus = {
        "PDF": ["Invoice", "Annual_Report", "Confidential", "Summary", "Draft_Q3"],
        "JPEG": ["Vacation", "IMG", "Screenshot", "Portrait", "Landscape_HQ"]
    }
    
    # Mock behavior of extracting top keywords
    available_keywords = keyword_corpus.get(file_type, ["Recovered", "Data"])
    selected_keywords = random.sample(available_keywords, min(2, len(available_keywords)))
    
    return f"{'_'.join(selected_keywords)}_{offset}.{file_type.lower()}"

def calculate_confidence(file_type: str) -> str:
    """Mock confidence rating based on magic bytes integrity."""
    return random.choice(["High", "Medium", "Low"])

@app.get("/api/scan/results", response_model=List[ScanResult])
def get_scan_results():
    """
    Ingests the 'candidates.json' contract generated by the C++ engine (Member 1)
    and serves it securely to the Next.js frontend (Member 3).
    """
    candidates_file = "candidates.json"
    results = []
    
    if os.path.exists(candidates_file):
        with open(candidates_file, "r") as f:
            try:
                candidates = json.load(f)
                for idx, candidate in enumerate(candidates):
                    file_type = candidate.get("type", "UNKNOWN")
                    offset = candidate.get("offset", 0)
                    
                    results.append(ScanResult(
                        id=idx + 1,
                        type=file_type,
                        offset=offset,
                        suggested_name=dummy_nlp_auto_naming(file_type, offset),
                        confidence=calculate_confidence(file_type)
                    ))
            except json.JSONDecodeError:
                pass # Fallback if JSON is incomplete/locked
                
    return results
